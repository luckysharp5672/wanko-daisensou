export function getUnitDef(id) {
  return UNIT_DEFS.find((u) => u.id === id);
}

export function getLevelMultiplier(level) {
  const perLevel = 1 + (Math.max(1, level) - 1) * LEVEL_PER_STEP;
  return perLevel * FORM_BONUS[getFormIndex(level)];
}

// レーダーチャート用のステータス最大値（全キャラの基礎値中の最大値。正規化の基準にする）
const STAT_MAX = {
  hp: Math.max(...UNIT_DEFS.map((u) => u.hp)),
  atk: Math.max(...UNIT_DEFS.map((u) => u.atk)),
  range: Math.max(...UNIT_DEFS.map((u) => u.range)),
  speed: Math.max(...UNIT_DEFS.map((u) => u.speed)),
  kb: Math.max(...UNIT_DEFS.map((u) => u.kb)),
};

// レーダーチャート用に5軸（HP/攻撃/射程/速度/耐久）を0〜1に正規化して返す。
// HP・攻撃力はレベル補正後の値、射程・速度・耐久はレベルで変化しない基礎値を使う。
export function getRadarStats(def, level) {
  const mult = getLevelMultiplier(level);
  const hp = Math.round(def.hp * mult);
  const atk = Math.round(def.atk * mult);
  return [
    { label: 'HP', value: hp, ratio: Math.min(1, hp / STAT_MAX.hp) },
    { label: '攻撃', value: atk, ratio: Math.min(1, atk / STAT_MAX.atk) },
    { label: '射程', value: def.range, ratio: Math.min(1, def.range / STAT_MAX.range) },
    { label: '速度', value: def.speed, ratio: Math.min(1, def.speed / STAT_MAX.speed) },
    { label: '耐久', value: def.kb, ratio: Math.min(1, def.kb / STAT_MAX.kb) },
  ];
}

export function getUpgradeCost(def, currentLevel, limitBreakCount = 0) {
  const cap = getEffectiveMaxLevel(def, limitBreakCount);
  if (currentLevel >= cap) return null;
  return Math.round(def.cost * (1.5 + currentLevel * 0.5));
}

let uidCounter = 0;

export function spawnAlly(defId, x, level = 1) {
  const def = getUnitDef(defId);
  if (!def) throw new Error(`unknown unit: ${defId}`);
  const mult = getLevelMultiplier(level);
  return {
    uid: `a${++uidCounter}`,
    defId,
    side: 'ally',
    name: def.name,
    icon: def.icon,
    layer: def.layer,
    level,
    form: getFormIndex(level),
    x,
    width: 34,
    hp: Math.round(def.hp * mult),
    maxHp: Math.round(def.hp * mult),
    atk: Math.round(def.atk * mult),
    atkInterval: def.atkInterval,
    range: def.range,
    speed: def.speed,
    kbRemaining: def.kb,
    strongAgainst: def.strongAgainst,
    nextAttackAt: 0,
    attackFlashUntil: 0,
    knockbackUntil: 0,
    engaged: false,
    dead: false,
  };
}
