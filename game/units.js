// プレイヤーキャラクター（わんこ側）データ定義
// layer: 戦いに参加できる層（sky=上空 / mid=中空 / ground=地面 / sea=海面）
// rarity: basic（最初から） / EX（章ボス撃破報酬） / rare・superrare・legend（ガチャ限定）

export const MAX_LEVEL = 30;
export const BASE_LEVEL_CAP = 5; // ガチャ限定キャラの初期レベル上限（限界突破前）
export const LIMIT_BREAK_STEP = 5; // 重複キャラ1体を素材にレベル上限を+5
const LEVEL_PER_STEP = 0.06; // レベル1につき HP/攻撃力 +6%（緩やかな成長）
const FORM_LEVEL_SPAN = 10; // 10レベルごとに進化
const FORM_BONUS = [1, 1.3, 1.7]; // 進化時の大幅ボーナス（第1形態/第2形態/第3形態）
export const FORM_SUFFIX = ['', '【改】', '【真】'];
export const FORM_BADGE = ['', '⚔️', '👑'];

// 基本キャラ（最初から仲間）は最初からLv上限まで育成可能。
// ガチャ限定キャラ（EX・レア・超激レア・伝説レア）は同キャラの重複入手を
// 限界突破の素材にして5レベルずつ上限を伸ばしていく必要がある。
export function getEffectiveMaxLevel(def, limitBreakCount = 0) {
  if (def.rarity === 'basic') return MAX_LEVEL;
  return Math.min(MAX_LEVEL, BASE_LEVEL_CAP + limitBreakCount * LIMIT_BREAK_STEP);
}

export function getFormIndex(level) {
  return Math.min(FORM_BONUS.length - 1, Math.floor(Math.max(1, level) / FORM_LEVEL_SPAN));
}

export function getFormSuffix(level) {
  return FORM_SUFFIX[getFormIndex(level)];
}

export function getFormBadge(level) {
  return FORM_BADGE[getFormIndex(level)];
}

// キャラ画像のパス（すべて assets/ 配下、index.htmlからの相対パス）
export function getStatusImage(defId) {
  return `assets/characters/status/${defId}.png`;
}

export function getBattleImage(defId) {
  return `assets/characters/battle/${defId}.png`;
}

// レアリティ別の「きらきら背景」。ステータス用画像の背景として重ねる
export function getKirakiraImage(rarity) {
  return `assets/kirakira/${rarity.toLowerCase()}.png`;
}

